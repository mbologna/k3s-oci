#!/usr/bin/env bash
# lib/common.sh -- shared OS-agnostic bootstrap helpers for k3s server and agent nodes.
# Pure bash -- no Terraform interpolation. Sourced by prepending to cloud-init scripts.
# Variables (K3S_VERSION, VAULT_SECRET_ID_K3S_TOKEN, etc.) are exported by
# the Terraform-rendered vars header (server-vars.sh.tpl / agent-vars.sh.tpl).
# OS-specific bootstrap (bootstrap() and configure_unattended_upgrades()) is provided
# by bootstrap-ubuntu.sh or bootstrap-opensuse.sh, prepended before this file by data.tf.
# shellcheck disable=SC2154

# Write a cluster-wide shared SSH host key so that all nodes behind the NLB
# present the same fingerprint (eliminates "REMOTE HOST IDENTIFICATION HAS CHANGED").
# The key is generated by Terraform and distributed via cloud-init as base64.
setup_shared_ssh_host_key() {
  # Decode to a temp file first; a partial decode (malformed base64) would
  # write a truncated key and silently break SSH on the next connection.
  local tmp_key
  tmp_key=$(mktemp)
  if ! echo "${SSH_HOST_KEY_PRIVATE_B64}" | base64 -d > "${tmp_key}"; then
    rm -f "${tmp_key}"
    echo "ERROR: base64 decode of SSH_HOST_KEY_PRIVATE_B64 failed — shared SSH host key not installed."
    exit 1
  fi
  mv "${tmp_key}" /etc/ssh/ssh_host_ed25519_key
  printf '%s\n' "${SSH_HOST_KEY_PUBLIC}"          > /etc/ssh/ssh_host_ed25519_key.pub
  chmod 600 /etc/ssh/ssh_host_ed25519_key
  chmod 644 /etc/ssh/ssh_host_ed25519_key.pub
  # Service name is "ssh" on Ubuntu/Debian and "sshd" on openSUSE/RHEL.
  systemctl restart ssh 2>/dev/null || systemctl restart sshd
}

# -- Longhorn prerequisites ----------------------------------------------------

configure_longhorn_prereqs() {
  # Stale iSCSI sessions: Longhorn opens a session per volume to the pod IP of
  # the current replica. When that replica moves (an instance-manager restart,
  # a k3s upgrade), the old session keeps reconnecting to an IP that is gone,
  # and iscsid refuses to log it out mid-reconnect. With the stock
  # replacement_timeout of 6000 s (100 min) the volume can't attach on its new
  # engine for that long; a PVC stayed "attaching" for over an hour. 120 s lets
  # the dead session go so the new one takes over.
  if grep -q '^node.session.timeo.replacement_timeout' /etc/iscsi/iscsid.conf 2>/dev/null; then
    sed -i 's/^node.session.timeo.replacement_timeout.*/node.session.timeo.replacement_timeout = 120/' \
      /etc/iscsi/iscsid.conf
  else
    echo 'node.session.timeo.replacement_timeout = 120' >>/etc/iscsi/iscsid.conf
  fi

  # Keep multipathd off Longhorn volumes: every Longhorn iSCSI disk reports the
  # same vendor/product (IET VIRTUAL-DISK) and WWID. With find_multipaths "on"
  # (Ubuntu's default) multipathd takes two attached Longhorn volumes for two
  # paths to one LUN and from then on wraps each new one in an mpath device;
  # the CSI mount of the raw device then fails ("already mounted or mount
  # point busy") and the pod hangs in ContainerCreating. The OCI boot volume is
  # not multipathed, so blacklisting only Longhorn's disks changes nothing
  # else. A conf.d drop-in leaves the distribution's multipath.conf alone.
  mkdir -p /etc/multipath/conf.d
  cat >/etc/multipath/conf.d/longhorn.conf <<'EOF'
# Written by k3s-oci cloud-init: keep multipathd off Longhorn's iSCSI disks.
blacklist {
    device {
        vendor "IET"
        product "VIRTUAL-DISK"
    }
}
EOF
  if systemctl is-active --quiet multipathd.service; then
    systemctl reload multipathd.service || systemctl restart multipathd.service || true
  fi

  systemctl enable iscsid.service
  systemctl restart iscsid.service
  modprobe nfs || true
}

# -- flannel VXLAN FDB self-heal -----------------------------------------------
# A missing flannel.1 forwarding-database entry silently drops outbound VXLAN
# traffic: routing and DNAT succeed locally, the packet never leaves the node.
# It broke DNS for every pod on a cluster built from this module, and the kernel
# doesn't reliably rebuild the entry. A timer re-applies each peer's entry
# every 5 minutes, idempotently. Peers come from the flannel node annotations
# (VtepMAC in backend-data, underlay IP in public-ip), read with k3s's embedded
# flannel kubeconfig, which exists on servers and agents and may list nodes.

setup_flannel_fdb_fix() {
  cat >/usr/local/bin/flannel-fdb-fix.sh <<'EOF'
#!/bin/sh
# Written by k3s-oci cloud-init: re-apply missing flannel.1 FDB entries.
set -eu
KC=/var/lib/rancher/k3s/agent/k3scontroller.kubeconfig
# The kubectl k3s already unpacked: `k3s kubectl` from a freshly upgraded binary
# first unpacks its own data dir, which this sandbox can't write. current/ moves
# only once the new k3s has started.
KUBECTL=/var/lib/rancher/k3s/data/current/bin/kubectl
[ -x "$KUBECTL" ] || KUBECTL="k3s kubectl"
# Consecutive failed lookups, kept across runs: a k3s restart (an upgrade, a
# crash) takes the API away for minutes and shouldn't fail the unit; a lookup
# still failing after 6 runs (30 min) should.
FAILS=/run/flannel-fdb-fix/failures
ip link show flannel.1 >/dev/null 2>&1 || { echo "flannel-fdb-fix: flannel.1 not found, skipping" >&2; exit 0; }
[ -r "$KC" ] || { echo "flannel-fdb-fix: $KC not found, skipping" >&2; exit 0; }
SELF_MAC=$(cat /sys/class/net/flannel.1/address)
# Captured first: in a pipeline a kubectl failure would go unnoticed (no pipefail in sh).
if ! PEERS=$($KUBECTL --kubeconfig "$KC" get nodes -o jsonpath='{range .items[*]}{.metadata.annotations.flannel\.alpha\.coreos\.com/public-ip} {.metadata.annotations.flannel\.alpha\.coreos\.com/backend-data}{"\n"}{end}'); then
    n=$(( $(cat "$FAILS" 2>/dev/null || echo 0) + 1 ))
    echo "$n" >"$FAILS"
    [ "$n" -ge 6 ] && { echo "flannel-fdb-fix: cannot list nodes, $n runs in a row" >&2; exit 1; }
    echo "flannel-fdb-fix: cannot list nodes (run $n of 6 before failing), skipping" >&2
    exit 0
fi
rm -f "$FAILS"
printf '%s\n' "$PEERS" | while read -r ip data; do
    mac=$(printf '%s' "$data" | sed -n 's/.*"VtepMAC":"\([^"]*\)".*/\1/p')
    [ -n "$ip" ] && [ -n "$mac" ] && [ "$mac" != "$SELF_MAC" ] || continue
    if bridge fdb show dev flannel.1 | grep -qi "^$mac dst $ip "; then
        echo "flannel-fdb-fix: $mac dst $ip already present"
    else
        bridge fdb replace "$mac" dst "$ip" dev flannel.1
        echo "flannel-fdb-fix: added missing entry $mac dst $ip"
    fi
done
EOF
  chmod 0755 /usr/local/bin/flannel-fdb-fix.sh

  cat >/etc/systemd/system/flannel-fdb-fix.service <<'EOF'
[Unit]
Description=Re-apply missing flannel VXLAN FDB entries (idempotent)
After=network-online.target
Wants=network-online.target

[Service]
Type=oneshot
ExecStart=/usr/local/bin/flannel-fdb-fix.sh
# It only reads the node list through the API and rewrites flannel.1's FDB over
# netlink: CAP_NET_ADMIN and a throwaway kubectl cache are all it needs.
Environment=KUBECACHEDIR=/tmp/kube-cache
# The script's failure counter; kept between runs.
RuntimeDirectory=flannel-fdb-fix
RuntimeDirectoryPreserve=yes
NoNewPrivileges=true
ProtectSystem=strict
ProtectHome=read-only
PrivateTmp=true
PrivateDevices=true
CapabilityBoundingSet=CAP_NET_ADMIN
RestrictAddressFamilies=AF_UNIX AF_INET AF_INET6 AF_NETLINK
MemoryDenyWriteExecute=true
ProtectKernelTunables=true
ProtectKernelModules=true
ProtectKernelLogs=true
ProtectControlGroups=true
ProtectClock=true
ProtectHostname=true
RestrictSUIDSGID=true
RestrictRealtime=true
RestrictNamespaces=true
LockPersonality=true
SystemCallArchitectures=native
EOF

  cat >/etc/systemd/system/flannel-fdb-fix.timer <<'EOF'
[Unit]
Description=Periodically re-apply missing flannel VXLAN FDB entries

[Timer]
OnBootSec=2min
OnUnitActiveSec=5min

[Install]
WantedBy=timers.target
EOF
  systemctl daemon-reload
  systemctl enable --now flannel-fdb-fix.timer
}

# -- OCI CLI -------------------------------------------------------------------
# Always installed on server nodes (required for first-server election via
# instance_principal auth). Installed on agent nodes only when Vault is enabled.

install_oci_cli() {
  if /root/bin/oci --version &>/dev/null 2>&1; then
    echo "OCI CLI already installed, skipping."
    return 0
  fi
  bash -c "$(curl -sfL https://raw.githubusercontent.com/oracle/oci-cli/master/scripts/install/install.sh)" \
    -- --accept-all-defaults
  # Suppress announcements so they never pollute stdout of subsequent oci commands
  # (announcements on stdout break pipes to jq / base64). Use python3 to set the
  # key idempotently in [OCI_CLI_SETTINGS] rather than blindly appending.
  python3 - <<'RCEOF'
import configparser, os
rc = os.path.expanduser('~/.oci/oci_cli_rc')
os.makedirs(os.path.dirname(rc), exist_ok=True)
cfg = configparser.ConfigParser()
cfg.read(rc)
if not cfg.has_section('OCI_CLI_SETTINGS'):
    cfg.add_section('OCI_CLI_SETTINGS')
cfg.set('OCI_CLI_SETTINGS', 'suppress_feedback', 'True')
with open(rc, 'w') as f:
    cfg.write(f)
RCEOF
}

# -- Helm ----------------------------------------------------------------------

install_helm() {
  command -v helm &>/dev/null && return 0
  curl -fsSL https://raw.githubusercontent.com/helm/helm/main/scripts/get-helm-3 | bash || {
    echo "ERROR: Helm install failed."
    return 1
  }
}

# -- Network helpers -----------------------------------------------------------
# Resolve node IP and flannel interface from K3S_SUBNET when a specific subnet
# CIDR is provided. Sets LOCAL_IP and FLANNEL_IFACE in the caller's scope.
# Used by both server and agent install functions.

resolve_flannel_params() {
  if [[ "${K3S_SUBNET}" != "default_route_table" ]]; then
    export LOCAL_IP
    export FLANNEL_IFACE
    LOCAL_IP=$(ip -4 route ls "${K3S_SUBNET}" | grep -Po '(?<=src )(\S+)')
    FLANNEL_IFACE=$(ip -4 route ls "${K3S_SUBNET}" | grep -Po '(?<=dev )(\S+)')
    if [[ -z "${LOCAL_IP}" || -z "${FLANNEL_IFACE}" ]]; then
      echo "ERROR: resolve_flannel_params: could not determine LOCAL_IP or FLANNEL_IFACE from subnet '${K3S_SUBNET}'."
      echo "  'ip -4 route ls ${K3S_SUBNET}' returned no usable result."
      echo "  Check that K3S_SUBNET matches an interface route on this node."
      exit 1
    fi
  fi
}

# setup_etcd_snapshot_upload
# Installs a cron job that takes a k3s etcd snapshot and uploads it to OCI Object
# Storage every 6 hours using OCI CLI instance_principal auth (no S3 credentials).
# Requires ETCD_SNAPSHOT_BUCKET and OCI_OBJECT_NAMESPACE to be non-empty.
# Installed on ALL server nodes. Each server uploads under its own hostname
# prefix (no name collisions); pruning covers the whole cluster prefix so
# snapshots left behind by replaced servers age out instead of piling up.

setup_etcd_snapshot_upload() {
  if [[ "${ENABLE_ETCD_SNAPSHOTS:-false}" != "true" ]] \
     || [[ -z "${ETCD_SNAPSHOT_BUCKET:-}" ]] \
     || [[ -z "${OCI_OBJECT_NAMESPACE:-}" ]]; then
    echo "INFO: etcd snapshot upload not configured (ENABLE_ETCD_SNAPSHOTS=${ENABLE_ETCD_SNAPSHOTS:-false})."
    return 0
  fi

  local upload_script="/usr/local/bin/etcd-snapshot-upload.sh"
  local retain="${ETCD_SNAPSHOT_RETENTION:-5}"

  # Compute a stable per-node cron offset (0, 2, or 4 min) from the last octet
  # of the primary IP to stagger multiple server crons so they don't run at
  # exactly the same minute. Prevents concurrent k3s etcd-snapshot save calls and prune
  # races on the same Object Storage prefix.
  local node_ip cron_offset octet
  node_ip=$(hostname -I 2>/dev/null | awk '{print $1}' || echo "0.0.0.0")
  # Guard against empty hostname -I at early boot: ${node_ip##*.} would be empty,
  # causing $(( (% 3)*2 )) arithmetic syntax error → set -e abort.
  octet="${node_ip##*.}"
  cron_offset=$(( (${octet:-0} % 3) * 2 ))

  cat > "${upload_script}" << 'ETCD_SCRIPT'
#!/usr/bin/env bash
# Cron-managed etcd snapshot upload to OCI Object Storage via instance_principal.
# Installed by cloud-init; edit /etc/cron.d/etcd-snapshot-upload to reschedule.
# Each server uploads under its own hostname prefix; prune spans the cluster prefix.
set -euo pipefail

export OCI_CLI_AUTH=instance_principal
export PATH="/root/bin:$PATH"

SNAPSHOT_DIR="/var/lib/rancher/k3s/server/db/snapshots"
BUCKET="__ETCD_BUCKET__"
NAMESPACE="__OCI_NAMESPACE__"
CLUSTER="__CLUSTER_NAME__"
RETAIN=__RETAIN__
NODE_NAME="$(hostname -s)"

SNAPSHOT_NAME="etcd-snapshot-${CLUSTER}-${NODE_NAME}-$(date -u +%Y%m%d-%H%M%S)"
echo "[$(date -u)] Creating etcd snapshot: ${SNAPSHOT_NAME}"

k3s etcd-snapshot save --name "${SNAPSHOT_NAME}" 2>&1 || {
  echo "[$(date -u)] ERROR: k3s etcd-snapshot save failed." >&2
  exit 1
}

SNAPSHOT_FILE=$(find "${SNAPSHOT_DIR}" -name "${SNAPSHOT_NAME}*" -type f | head -1)
if [[ -z "${SNAPSHOT_FILE}" ]]; then
  echo "[$(date -u)] ERROR: Snapshot file not found for ${SNAPSHOT_NAME}" >&2
  exit 1
fi

CLUSTER_PREFIX="etcd-snapshots/${CLUSTER}"
NODE_PREFIX="${CLUSTER_PREFIX}/${NODE_NAME}"
echo "[$(date -u)] Uploading $(basename "${SNAPSHOT_FILE}") to oci://${BUCKET}/${NODE_PREFIX}/"
oci os object put \
  --namespace "${NAMESPACE}" \
  --bucket-name "${BUCKET}" \
  --name "${NODE_PREFIX}/$(basename "${SNAPSHOT_FILE}")" \
  --file "${SNAPSHOT_FILE}" \
  --no-multipart

# Prune across the whole cluster prefix, not just this node's: every server's
# snapshot holds the same etcd data, and a replaced server's prefix would
# otherwise never be pruned (its hostname never runs this script again).
echo "[$(date -u)] Pruning old snapshots for ${CLUSTER} (keeping last ${RETAIN})..."
oci os object list \
  --namespace "${NAMESPACE}" \
  --bucket-name "${BUCKET}" \
  --prefix "${CLUSTER_PREFIX}/" \
  --fields name,timeCreated \
  --all \
  --query "sort_by(data, &\"time-created\")[:-${RETAIN}].name" \
  --raw-output 2>/dev/null \
  | python3 -c "import sys,json; [print(x) for x in (json.load(sys.stdin) or [])]" 2>/dev/null \
  | while IFS= read -r old_obj; do
      [[ -z "${old_obj}" ]] && continue
      echo "[$(date -u)]   Deleting: ${old_obj}"
      oci os object delete \
        --namespace "${NAMESPACE}" \
        --bucket-name "${BUCKET}" \
        --object-name "${old_obj}" \
        --force 2>/dev/null || true
    done

echo "[$(date -u)] etcd snapshot upload complete."
ETCD_SCRIPT

  # Substitute placeholders with actual values
  sed -i "s|__ETCD_BUCKET__|${ETCD_SNAPSHOT_BUCKET}|g" "${upload_script}"
  sed -i "s|__OCI_NAMESPACE__|${OCI_OBJECT_NAMESPACE}|g" "${upload_script}"
  sed -i "s|__CLUSTER_NAME__|${CLUSTER_NAME}|g" "${upload_script}"
  sed -i "s|__RETAIN__|${retain}|g" "${upload_script}"
  chmod +x "${upload_script}"

  # Staggered schedule: offset 0, 2, or 4 min based on node IP last octet.
  echo "${cron_offset} */6 * * * root ${upload_script} >> /var/log/etcd-snapshot-upload.log 2>&1" \
    > /etc/cron.d/etcd-snapshot-upload

  # Run an initial snapshot immediately — but only if this node is the elected first server
  # and etcd is ready. Joining servers may not have been promoted to voter status yet;
  # running 'k3s etcd-snapshot save' on a learner produces a noisy warning and an empty snapshot.
  if [[ "${IS_FIRST_SERVER:-false}" == "true" ]]; then
    echo "Running initial etcd snapshot upload (first server only)..."
    "${upload_script}" || echo "WARNING: Initial snapshot upload failed — check /var/log/etcd-snapshot-upload.log"
  else
    echo "Joining server — skipping immediate snapshot; cron will run within 6h."
  fi

  echo "etcd snapshot cron job installed (every 6h at minute ${cron_offset}; retaining last ${retain} snapshots per node)."
}


# Retries up to 20 times (30s gap = ~10 min) to handle IAM dynamic-group
# propagation delay on newly launched instances.
# Diagnostic output goes to stderr so it appears in the log even when this
# function is called inside a $() command substitution (which captures stdout).
fetch_from_vault() {
  local secret_id="$1"
  local max_attempts=20
  local delay=30
  local attempt=0
  local raw_value
  while [[ $attempt -lt $max_attempts ]]; do
    attempt=$((attempt + 1))
    if raw_value=$(oci secrets secret-bundle get \
      --secret-id "${secret_id}" \
      --query 'data."secret-bundle-content".content' \
      --raw-output 2>&1); then
      # Validate and decode; a malformed response would silently pass garbage downstream.
      local decoded
      if ! decoded=$(echo "${raw_value}" | base64 -d 2>/dev/null) || [[ -z "${decoded}" ]]; then
        echo "Vault fetch attempt ${attempt}/${max_attempts}: base64 decode failed or empty — retrying..." >&2
        sleep "${delay}"
        continue
      fi
      echo "${decoded}"
      return 0
    fi
    echo "Vault fetch attempt ${attempt}/${max_attempts} failed, retrying in ${delay}s..." >&2
    sleep "${delay}"
  done
  echo "ERROR: Failed to fetch secret '${secret_id}' from OCI Vault after ${max_attempts} attempts." >&2
  return 1
}

# resolve_k3s_token [needs_oci_cli]
# Fetches K3S_TOKEN from OCI Vault with plaintext fallback, then exports it.
# Pass "needs_oci_cli" on agent nodes where OCI CLI is not yet installed
# (servers already install it unconditionally via install_oci_cli()).

resolve_k3s_token() {
  if [[ "${1:-}" == "needs_oci_cli" ]]; then
    export OCI_CLI_AUTH=instance_principal
    export PATH="/root/bin:$PATH"
    install_oci_cli
  fi

  if [[ -n "${VAULT_SECRET_ID_K3S_TOKEN}" ]]; then
    echo "Fetching k3s token from OCI Vault..."
    if K3S_TOKEN=$(fetch_from_vault "${VAULT_SECRET_ID_K3S_TOKEN}"); then
      echo "Vault fetch successful."
    else
      echo "WARNING: Vault fetch failed — falling back to plaintext token from user-data." >&2
      K3S_TOKEN="${K3S_TOKEN_PLAIN}"
      [[ -z "${K3S_TOKEN}" ]] && { echo "ERROR: K3S_TOKEN_PLAIN is empty — cannot continue." >&2; exit 1; }
    fi
  else
    K3S_TOKEN="${K3S_TOKEN_PLAIN}"
  fi
  export K3S_TOKEN
}
